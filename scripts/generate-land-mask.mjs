// Rasterises Natural Earth 110m land into the committed run-length mask `src/lib/land-mask.ts`.
// Run once (or when the grid changes):  node scripts/generate-land-mask.mjs [path/to/land-110m.json]
// Without an argument it downloads world-atlas@2.0.2 land-110m.json (Natural Earth, public domain) from jsDelivr.
// Dependency-free on purpose: the TopoJSON decoding and the point-in-polygon test are written out below, so
// nothing from d3 / topojson / world-atlas is ever installed or reaches the site bundle.
import { readFile, writeFile } from 'node:fs/promises';

const PITCH = 2.5; // degrees per grid cell (equirectangular)
const LAT_MAX = 78;
const LAT_MIN = -56;
const URL_SRC = 'https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json';

const arg = process.argv[2];
const topo = JSON.parse(
  arg ? await readFile(arg, 'utf8') : await (await fetch(URL_SRC)).text(),
);

// Decode delta-encoded, quantised arcs into [lon, lat] coordinate lists.
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
const ring = (ids) =>
  ids.flatMap((id, i) => {
    const pts = id >= 0 ? arcs[id] : [...arcs[~id]].reverse();
    return i === 0 ? pts : pts.slice(1);
  });

// Collect every ring of every polygon; a point is land if it lies inside an odd number of rings (even-odd).
const rings = [];
for (const g of topo.objects.land.geometries) {
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  for (const poly of polys) for (const r of poly) rings.push(ring(r));
}

function inside(lon, lat, pts) {
  let c = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i];
    const [xj, yj] = pts[j];
    if (
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    )
      c = !c;
  }
  return c;
}
const isLand = (lon, lat) =>
  rings.reduce((n, r) => n + (inside(lon, lat, r) ? 1 : 0), 0) % 2 === 1;

const cols = Math.round(360 / PITCH);
const rows = Math.round((LAT_MAX - LAT_MIN) / PITCH);
const out = [];
for (let r = 0; r < rows; r++) {
  const lat = LAT_MAX - (r + 0.5) * PITCH;
  const runs = [];
  let start = -1;
  for (let c = 0; c <= cols; c++) {
    const land = c < cols && isLand(-180 + (c + 0.5) * PITCH, lat);
    if (land && start < 0) start = c;
    if (!land && start >= 0) {
      runs.push([start, c - start]);
      start = -1;
    }
  }
  out.push(runs);
}

const body = out
  .map((runs) => `  [${runs.map(([s, l]) => `[${s}, ${l}]`).join(', ')}],`)
  .join('\n');
await writeFile(
  new URL('../src/lib/land-mask.ts', import.meta.url),
  `// GENERATED by scripts/generate-land-mask.mjs. Do not edit by hand.
// Source: Natural Earth 110m land via world-atlas@2.0.2 (land-110m.json). Natural Earth is public domain.
// Regenerate: node scripts/generate-land-mask.mjs
// Grid: equirectangular, ${PITCH} degree cells, latitude ${LAT_MAX} to ${LAT_MIN}, longitude -180 to 180.
// A cell is land when its centre is inside the land polygons. Rows run north to south; each run is [startCol, length].

export const LAND_MASK = {
  pitch: ${PITCH},
  latMax: ${LAT_MAX},
  cols: ${cols},
  rows: [
${body}
  ] as [number, number][][],
};
`,
);
console.log(`wrote src/lib/land-mask.ts: ${rows} rows x ${cols} cols`);
